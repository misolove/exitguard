def _int(ip):
    """IP 문자열 → (버전 4/6, 정수). 해석 불가면 None."""
    try:
        return 4, int.from_bytes(socket.inet_pton(socket.AF_INET, ip), "big")
    except OSError:
        pass
    try:
        return 6, int.from_bytes(socket.inet_pton(socket.AF_INET6, ip), "big")
    except OSError:
        return None


class GeoDB:
    """정렬된 범위 표 + bisect. 같은 국가가 이어지는 범위는 합쳐서 메모리를 줄인다."""

    def __init__(self, path):
        self.path = path
        self.v4 = (array("L"), array("L"), [])   # 시작, 끝, 국가
        self.v6 = ([], [], [])
        opener = gzip.open if path.endswith(".gz") else open
        with opener(path, "rt", encoding="ascii", errors="replace") as f:
            for line in f:
                parts = line.strip().split(",")
                if len(parts) < 3:
                    continue
                a, b = _int(parts[0].strip('"')), _int(parts[1].strip('"'))
                cc = parts[2].strip('"').upper()
                if not a or not b or a[0] != b[0]:
                    continue
                starts, ends, ccs = self.v4 if a[0] == 4 else self.v6
                if ccs and ccs[-1] == cc and ends[-1] + 1 == a[1]:
                    ends[-1] = b[1]
                else:
                    starts.append(a[1]); ends.append(b[1]); ccs.append(cc)
        if not self.v4[0] and not self.v6[0]:
            raise ValueError("빈 GeoIP 파일")

    def country(self, ip):
        """국가 코드 또는 None (사설·예약 대역 'ZZ' 포함)."""
        v = _int(ip)
        if not v:
            return None
        starts, ends, ccs = self.v4 if v[0] == 4 else self.v6
        i = bisect.bisect_right(starts, v[1]) - 1
        if i < 0 or v[1] > ends[i] or ccs[i] in ("", "ZZ"):
            return None
        return ccs[i]


def load_settings(path=None):
    """geo.json (비밀값 없음, 0644) 읽기: {"db": 경로, "home": {"lat", "lon", "city"}}. 없으면 기본값."""
    try:
        with open(path or GEO_CFG) as f:
            cfg = json.load(f)
    except (OSError, ValueError):
        cfg = {}
    home = cfg.get("home")
    try:
        home = {"lat": float(home["lat"]), "lon": float(home["lon"]), "city": str(home.get("city") or "")}
    except (TypeError, KeyError, ValueError):
        home = None
    return {"db": cfg.get("db") or DEFAULT_DB, "home": home}
